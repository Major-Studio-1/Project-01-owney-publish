import {cp,mkdir,rm,writeFile,readFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(fileURLToPath(new URL('..',import.meta.url))),dist=path.resolve(root,'dist');
process.chdir(root);
await import('../prepare-data.cjs');
if(path.dirname(dist)!==root||path.basename(dist)!=='dist') throw new Error('Invalid build directory');
await rm(dist,{recursive:true,force:true});
await mkdir(path.join(dist,'server'),{recursive:true});
await mkdir(path.join(dist,'.openai'),{recursive:true});
await cp('public',path.join(dist,'client'),{recursive:true});
await cp('.openai/hosting.json',path.join(dist,'.openai/hosting.json'));
await cp('drizzle',path.join(dist,'.openai/drizzle'),{recursive:true});
const db=(await readFile('worker/db.js','utf8')).replace(/^export /gm,'');
const handler=(await readFile('worker/index.js','utf8')).replace(/^import .* from '\.\/db\.js';\r?\n/m,'');
await writeFile(path.join(dist,'server/index.js'),db+'\n'+handler);
await writeFile(path.join(dist,'server/wrangler.json'),JSON.stringify({name:'owney-a-life-in-tags',main:'index.js',compatibility_date:'2026-05-15',assets:{directory:'../client',binding:'ASSETS'},d1_databases:[{binding:'DB',database_name:'owney',database_id:'local-owney-preview',migrations_dir:'../.openai/drizzle'}]},null,2));
const output=await import('../dist/server/index.js');
if(typeof output.default?.fetch!=='function')throw new Error('Missing Worker fetch handler');
console.log('Built the visualization and shared collection.');
